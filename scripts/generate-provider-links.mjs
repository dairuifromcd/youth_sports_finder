import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { providerLinkLabels, safeProviderLinkUrl } from '../src/providerLinks.ts'

const record = value => typeof value === 'object' && value !== null && !Array.isArray(value)
const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0

/** Offline exact-ID overlay. Full candidate/evidence records stay outside the browser. */
export function buildProviderDisplayLinks(research, validated) {
  if (!record(research) || research.schemaVersion !== 3 || !Array.isArray(research.providers) ||
    !record(validated) || !Array.isArray(validated.providers) || !validated.providers.length) {
    throw new Error('Invalid provider link input schema')
  }
  const originals = new Map()
  for (const provider of validated.providers) {
    if (!record(provider) || typeof provider.id !== 'string' || !provider.id ||
      typeof provider.name !== 'string' || !provider.name || originals.has(provider.id)) {
      throw new Error('Invalid or duplicate original provider identity')
    }
    originals.set(provider.id, provider)
  }
  const overlay = new Map()
  const candidates = new Set()
  const urlOwners = new Map()
  for (const provider of research.providers) {
    const original = originals.get(provider?.providerId)
    if (!original || overlay.has(provider.providerId) || provider.providerName !== original.name ||
      provider.suburb !== original.suburb || !Array.isArray(provider.links)) {
      throw new Error(`Provider identity mismatch: ${provider?.providerId}`)
    }
    const links = []
    const seen = new Map()
    for (const link of provider.links) {
      if (!record(link) || link.providerId !== provider.providerId || link.providerName !== original.name ||
        typeof link.candidateId !== 'string' || !link.candidateId.startsWith(`${provider.providerId}:r3:`) ||
        candidates.has(link.candidateId)) throw new Error(`Link identity mismatch: ${link?.candidateId}`)
      candidates.add(link.candidateId)
      if (link.confidence !== 'Verified' || link.recommendPublicDisplay !== true) continue
      if (link.entityRelationship !== 'provider' || link.purpose !== 'general_organisation' ||
        link.requiresManualReview !== false || link.actualAccess?.status !== 'accessible' ||
        !['public_web_page', 'public_organisation_metadata'].includes(link.actualAccess?.contentScope)) continue
      const url = safeProviderLinkUrl(link.url, link.linkType)
      if (!url) throw new Error(`Unsafe or type-mismatched recommended URL: ${link.candidateId}`)
      const key = url.replace(/\/(?=[?#]|$)/, '')
      const owner = urlOwners.get(key)
      if (owner && owner !== provider.providerId) throw new Error(`URL assigned to multiple providers: ${url}`)
      urlOwners.set(key, provider.providerId)
      if (seen.has(key)) {
        if (seen.get(key) !== link.linkType) throw new Error(`Conflicting duplicate URL type: ${url}`)
        continue
      }
      seen.set(key, link.linkType)
      links.push({ type: link.linkType, url })
    }
    overlay.set(provider.providerId, links)
  }
  if (overlay.size !== originals.size || [...originals.keys()].some(id => !overlay.has(id))) {
    throw new Error('Missing enrichment provider IDs')
  }
  return Object.fromEntries([...overlay].sort(([a], [b]) => compare(a, b)))
}

export function summarizeProviderLinks(links) {
  const all = Object.values(links).flat()
  return {
    providers: Object.keys(links).length,
    coveredProviders: Object.values(links).filter(items => items.length > 0).length,
    links: all.length,
    website: all.filter(link => providerLinkLabels[link.type] === 'Website').length,
    facebookPage: all.filter(link => link.type === 'facebook_page').length,
    facebookGroup: all.filter(link => link.type === 'facebook_group').length,
  }
}

export function renderProviderLinksModule(links, researchHash) {
  return `// Generated by npm run enrich:provider-links; do not edit by hand.\n` +
    `// Audit source: data/enrichment/provider-links-round3.json (SHA-256 ${researchHash}).\n` +
    `// Verified means organisation-link identity, not verified junior programs.\n` +
    `import type { ProviderDisplayLinks } from '../providerLinks'\n\n` +
    `export const providerDisplayLinks: ProviderDisplayLinks = ${JSON.stringify(links, null, 2)}\n`
}

function generate() {
  const researchBytes = readFileSync(new URL('../data/enrichment/provider-links-round3.json', import.meta.url))
  const validatedBytes = readFileSync(new URL('../data/benchmarks/qld-geocoder/stage-b/validated.json', import.meta.url))
  const research = JSON.parse(researchBytes)
  const validated = JSON.parse(validatedBytes)
  const sha256 = bytes => createHash('sha256').update(bytes).digest('hex')
  if (research.inputs?.inheritedProviderSourceSHA256 !== sha256(validatedBytes)) {
    throw new Error('Research provider source hash does not match validated.json')
  }
  const links = buildProviderDisplayLinks(research, validated)
  const summary = summarizeProviderLinks(links)
  const expected = { providers: 54, coveredProviders: 54, links: 95, website: 43, facebookPage: 50, facebookGroup: 2 }
  if (JSON.stringify(summary) !== JSON.stringify(expected)) throw new Error(`Round 3 completeness mismatch: ${JSON.stringify(summary)}`)
  const output = new URL('../src/data/providerLinks.ts', import.meta.url)
  const content = renderProviderLinksModule(links, sha256(researchBytes))
  if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8') !== content) throw new Error('Generated provider links are stale; run npm run enrich:provider-links')
  } else writeFileSync(output, content)
  console.log(JSON.stringify({ mode: process.argv.includes('--check') ? 'check' : 'generate', ...summary }))
}

if (process.argv[1] === fileURLToPath(import.meta.url)) generate()
